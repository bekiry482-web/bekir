import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name,root),'utf8');
const [html,css,domain,report,app,vendor] = await Promise.all(['index.html','style.css','domain.js','excel-report.js','app.js','node_modules/exceljs/dist/exceljs.min.js'].map(read));
await mkdir(new URL('vendor/',root),{recursive:true});
await writeFile(new URL('vendor/exceljs.min.js',root),vendor);
const clean = source => source.replace(/^import[^\n]+\n/gm,'').replaceAll('export ', '');
const js = clean(domain) + '\n' + clean(report) + '\n' + clean(app);
const license = await read('THIRD-PARTY-LICENSES.txt');
const result = html.replace('<head>',()=>`<head><!--\n${license.replaceAll('--','—')}\n-->`).replace('<script src="vendor/exceljs.min.js"></script>', ()=>`<script>${vendor.replace(/<\/script/gi, '<\\/script')}</script>`).replace('<link rel="stylesheet" href="style.css">', ()=>`<style>${css}</style>`).replace('<script type="module" src="app.js"></script>', ()=>`<script>\n${js}\n</script>`);
await writeFile(new URL('Fizyo.html',root),result);
